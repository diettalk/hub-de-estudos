-- Fase 2: Caderno de Erros
-- Rodar uma vez no Supabase: Painel > SQL Editor > New query > colar tudo > Run.

begin;

create table if not exists public.caderno_erros (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  disciplina_id bigint references public.paginas (id) on delete set null,
  disciplina_nome text not null check (char_length(disciplina_nome) between 1 and 200),
  assunto text not null check (char_length(assunto) between 1 and 200),
  banca text check (banca is null or char_length(banca) <= 100),
  ano smallint check (ano is null or ano between 1990 and 2100),
  enunciado text check (enunciado is null or char_length(enunciado) <= 2000),
  o_que_errei text not null check (char_length(o_que_errei) between 1 and 2000),
  motivo text not null check (motivo in ('atencao', 'conteudo', 'interpretacao', 'chute', 'outro')),
  aprendizado text not null check (char_length(aprendizado) between 1 and 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists caderno_erros_user_created_idx
  on public.caderno_erros (user_id, created_at desc);

alter table public.caderno_erros enable row level security;

drop policy if exists "caderno_erros_select_own" on public.caderno_erros;
create policy "caderno_erros_select_own" on public.caderno_erros
  for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "caderno_erros_insert_own" on public.caderno_erros;
create policy "caderno_erros_insert_own" on public.caderno_erros
  for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "caderno_erros_update_own" on public.caderno_erros;
create policy "caderno_erros_update_own" on public.caderno_erros
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "caderno_erros_delete_own" on public.caderno_erros;
create policy "caderno_erros_delete_own" on public.caderno_erros
  for delete to authenticated using ((select auth.uid()) = user_id);

-- Revisões geradas por um erro: somem junto quando o erro é apagado.
alter table public.revisoes
  add column if not exists caderno_erro_id bigint
  references public.caderno_erros (id) on delete cascade;

alter table public.revisoes alter column ciclo_sessao_id drop not null;

create index if not exists revisoes_caderno_erro_idx
  on public.revisoes (caderno_erro_id);

commit;
